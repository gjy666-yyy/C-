#include <iostream>
using namespace std;

int main()
{
	// 1.短整型：short
	short a = 10;
	// 2.整型：int
	int b = 20;
	// 3.长整型：long
	long c = 30;
	// 4.长长整型：long long
	long long d = 40;
	int sun = a + b + c + d;
	cout << "a" <<a<<endl;
	cout << "b" <<b<<endl;
	cout << "c" <<c<<endl;
	cout << "d" <<d<< endl;
	cout << sun << endl;
	 

	return 0;
}